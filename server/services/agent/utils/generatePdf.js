
import PDFDocument from "pdfkit";

const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "NexusAI",
        Title: data.title,
        Creator: "NexusAI",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", (error) => reject(error));

    // Title
    doc
      .fillColor("#111827")
      .font("Helvetica-Bold")
      .fontSize(24)
      .text(data.title || "Untitled Document", {
        align: "center",
      });

    if (data.subtitle) {
      doc.moveDown(0.5);

      doc
        .fillColor("#6B7280")
        .font("Helvetica")
        .fontSize(12)
        .text(data.subtitle, {
          align: "center",
        });
    }

    doc.moveDown(2);

    // Sections
    data?.sections?.forEach((s) => {
      doc
        .fillColor("#111827")
        .font("Helvetica-Bold")
        .fontSize(16)
        .text(s.heading || "");

      doc.moveDown(0.5);

      s?.points?.forEach((p) => {
        doc
          .fillColor("#374151")
          .font("Helvetica")
          .fontSize(11)
          .text("•  " + p, {
            indent: 5,
            lineGap: 3,
          });

        doc.moveDown(0.4);
      });

      doc.moveDown(0.8);
    });

    // Footer
    doc.moveDown(0.5);

    doc
      .fillColor("#9CA3AF")
      .font("Helvetica")
      .fontSize(9)
      .text("Generated by NexusAI", {
        align: "center",
      });

    doc.end();
  });
};

export default generatePdf;
