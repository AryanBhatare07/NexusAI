import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "64748B",
  blueLight: "EFF6FF",
  blueText: "DBEAFE",
};

export const generatePpt = async (data) => {
  const ppt = new pptxgen();

  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "NexusAI";
  ppt.title = data.title || "Presentation";
  ppt.subject = data.title || "Presentation";
  ppt.company = "NexusAI";
  ppt.lang = "en-US";

  ppt.theme = {
    headFontFace: "Aptos Display",
    bodyFontFace: "Aptos",
    lang: "en-US",
  };

  const slides = data?.slides || [];

  addCover(ppt, data);

  slides.forEach((s, i) => {
    addContentSlide(ppt, s.title, s.points, i + 2, slides.length + 2);
  });

  addThankYou(ppt);

  return ppt;
};

// Cover Slide
const addCover = (ppt, data) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.secondary,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.16,
    fill: { color: COLORS.primary },
    line: { color: COLORS.primary },
  });

  slide.addShape(ppt.ShapeType.rect, {
    x: 0.8,
    y: 2.05,
    w: 0.08,
    h: 1.5,
    fill: { color: "60A5FA" },
    line: { color: "60A5FA" },
  });

  slide.addText(data.title || "Untitled Presentation", {
    x: 1.15,
    y: 2.1,
    w: 10.8,
    h: 1.1,
    fontSize: 32,
    bold: true,
    color: COLORS.white,
    fit: "shrink",
    valign: "mid",
    breakLine: false,
  });

  slide.addText(data.subtitle || "A presentation by NexusAI", {
    x: 1.2,
    y: 3.35,
    w: 10.5,
    h: 0.5,
    fontSize: 17,
    color: COLORS.blueText,
    fit: "shrink",
  });

  slide.addShape(ppt.ShapeType.line, {
    x: 1.2,
    y: 4.15,
    w: 3,
    h: 0,
    line: {
      color: COLORS.primary,
      width: 2,
    },
  });

  slide.addText("GENERATED BY NEXUSAI", {
    x: 0.8,
    y: 6.85,
    w: 4,
    h: 0.25,
    fontSize: 10,
    bold: true,
    charSpacing: 2,
    color: "94A3B8",
  });
};

// Content Slides
const addContentSlide = (ppt, title, points, page, total) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.white,
  };

  // Top accent
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.12,
    fill: { color: COLORS.primary },
    line: { color: COLORS.primary },
  });

  // Slide Title
  slide.addText(title || "Untitled Section", {
    x: 0.7,
    y: 0.45,
    w: 11.9,
    h: 0.55,
    fontSize: 25,
    bold: true,
    color: COLORS.secondary,
    fit: "shrink",
  });

  // Divider
  slide.addShape(ppt.ShapeType.line, {
    x: 0.7,
    y: 1.15,
    w: 11.9,
    h: 0,
    line: {
      color: COLORS.border,
      width: 1.2,
    },
  });

  const visiblePoints = (points || []).slice(0, 6);

  visiblePoints.forEach((point, index) => {
    const y = 1.5 + index * 0.78;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.8,
      y,
      w: 11.7,
      h: 0.62,
      rectRadius: 0.08,
      fill: {
        color: index % 2 === 0 ? COLORS.blueLight : COLORS.light,
      },
      line: {
        color: COLORS.border,
        width: 0.7,
      },
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: 1.05,
      y: y + 0.23,
      w: 0.14,
      h: 0.14,
      fill: {
        color: COLORS.primary,
      },
      line: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(point), {
      x: 1.4,
      y: y + 0.1,
      w: 10.7,
      h: 0.42,
      fontSize: 15,
      color: COLORS.text,
      valign: "mid",
      fit: "shrink",
      breakLine: false,
    });
  });

  // Footer - outside the points loop
  slide.addShape(ppt.ShapeType.line, {
    x: 0.7,
    y: 6.75,
    w: 11.9,
    h: 0,
    line: {
      color: COLORS.border,
      width: 0.8,
    },
  });

  slide.addText("NEXUSAI", {
    x: 0.7,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 9,
    bold: true,
    charSpacing: 1.5,
    color: COLORS.muted,
  });

  slide.addText(`${page} / ${total}`, {
    x: 11.5,
    y: 6.9,
    w: 1.1,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
    align: "right",
  });
};

